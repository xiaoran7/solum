#!/usr/bin/env node
'use strict';
// Regenerates crates/solum-app/gen/android/tauri.settings.gradle on machines
// where the Tauri CLI has not run for this checkout.
//
// Why this exists: `settings.gradle` does `apply from: 'tauri.settings.gradle'`
// unconditionally, but that file is written by `tauri android init/build` with
// machine-local absolute paths and is gitignored — so a fresh checkout (CI,
// a new machine) cannot run any gradle task until it exists. This script
// rebuilds the same shape from what the repo itself knows: the path
// dependencies of solum-app that ship an `android/` directory, plus the tauri
// crates resolved to their exact Cargo.lock versions inside the local cargo
// registry. Run `cargo metadata --format-version 1 >/dev/null` first so the
// registry sources are downloaded and extracted.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const root = path.resolve(__dirname, '..');
const appTomlPath = path.join(root, 'crates', 'solum-app', 'Cargo.toml');
const lockPath = path.join(root, 'Cargo.lock');
const outPath = path.join(
  root, 'crates', 'solum-app', 'gen', 'android', 'tauri.settings.gradle'
);
const outBuildGradlePath = path.join(
  root, 'crates', 'solum-app', 'gen', 'android', 'app', 'tauri.build.gradle.kts'
);

const appToml = fs.readFileSync(appTomlPath, 'utf8');
const lock = fs.readFileSync(lockPath, 'utf8');

// --- collect gradle projects -------------------------------------------------

const projects = []; // { name, dir }

// 1) Path dependencies of solum-app that ship an android/ directory — the
// same rule the tauri CLI applies when it generates this file.
const pathDep =
  /^([A-Za-z0-9_-]+)\s*=\s*\{\s*path\s*=\s*"([^"]+)"/gm;
for (const [, name, rel] of appToml.matchAll(pathDep)) {
  const crateDir = path.resolve(path.dirname(appTomlPath), rel);
  const androidDir = path.join(crateDir, 'android');
  if (fs.existsSync(androidDir)) {
    projects.push({ name, dir: androidDir });
  }
}

// 2) tauri and tauri-plugin-* registry dependencies. `tauri` itself maps to
// the `mobile/android` gradle project named `:tauri-android`; plugins map to
// their `android/` directory under their own name.
const regDep =
  /^(tauri(?:-plugin-[a-z0-9-]+)?)\s*=\s*(?:\{[^}]*?version\s*=\s*"([^"]+)"|"([^"]+)")/gm;
const registryDeps = [];
for (const [, name, verInTable, verPlain] of appToml.matchAll(regDep)) {
  registryDeps.push({ name, requirement: verInTable || verPlain });
}

// Exact versions come from Cargo.lock — the requirement in Cargo.toml is
// often just "2", which is useless for finding a directory.
const lockBlocks = lock.split('[[package]]');
function lockedVersion(name) {
  for (const block of lockBlocks) {
    const m = block.match(new RegExp(`^\\s*name\\s*=\\s*"${name}"\\s*$`, 'm'));
    if (m) {
      const v = block.match(/^\s*version\s*=\s*"([^"]+)"/m);
      if (v) return v[1];
    }
  }
  return null;
}

const cargoHome = process.env.CARGO_HOME || path.join(os.homedir(), '.cargo');
const registrySrc = path.join(cargoHome, 'registry', 'src');
function registryDir(name, version) {
  if (!version || !fs.existsSync(registrySrc)) return null;
  for (const hash of fs.readdirSync(registrySrc)) {
    const dir = path.join(registrySrc, hash, `${name}-${version}`);
    if (fs.existsSync(dir)) return dir;
  }
  return null;
}

for (const { name } of registryDeps) {
  const version = lockedVersion(name);
  const src = registryDir(name, version);
  if (!src) {
    console.error(
      `gen-android-ci-settings: cannot locate ${name}@${version || '?'} under ${registrySrc}. ` +
        `Run \`cargo metadata --format-version 1 >/dev/null\` first so the sources are extracted.`
    );
    process.exit(1);
  }
  const isTauriCore = name === 'tauri';
  const dir = isTauriCore ? path.join(src, 'mobile', 'android') : path.join(src, 'android');
  if (!fs.existsSync(dir)) {
    console.error(`gen-android-ci-settings: ${dir} does not exist for ${name}@${version}`);
    process.exit(1);
  }
  projects.push({ name: isTauriCore ? 'tauri-android' : name, dir });
}

projects.sort((a, b) => a.name.localeCompare(b.name));

// --- emit --------------------------------------------------------------------

const lines = [
  '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
  '// Regenerated by scripts/gen-android-ci-settings.mjs (the tauri CLI writes',
  '// the same shape with machine-local paths; the file is gitignored).',
];
for (const p of projects) {
  lines.push(`include ':${p.name}'`);
  lines.push(`project(':${p.name}').projectDir = new File(${JSON.stringify(p.dir)})`);
}
fs.writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`gen-android-ci-settings: wrote ${outPath} (${projects.length} projects)`);

const buildLines = [
  '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
  'val implementation by configurations',
  'dependencies {',
  '  implementation("androidx.lifecycle:lifecycle-process:2.10.0")',
];
for (const p of projects) {
  buildLines.push(`  implementation(project(":${p.name}"))`);
}
buildLines.push('}');
fs.writeFileSync(outBuildGradlePath, buildLines.join('\n') + '\n');
console.log(`gen-android-ci-settings: wrote ${outBuildGradlePath}`);
